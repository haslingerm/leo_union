// Generates the union types and their contract tests.
// Run from the repository root:  dotnet run tools/Generate.cs
// CI runs it and fails if the checked-in files differ from the output.

using System.Text;

const int MinArity = 2;
const int MaxArity = 10;

string root = Directory.GetCurrentDirectory();
if (!File.Exists(Path.Combine(root, "LeoUnion.slnx")))
{
    Console.Error.WriteLine("Run this from the repository root (the folder containing LeoUnion.slnx).");
    return 1;
}

Write(Path.Combine(root, "LeoUnion", "Union.g.cs"), GenerateUnions());
Write(Path.Combine(root, "LeoUnion.Tests", "ContractTests.g.cs"), GenerateContractTests());
return 0;

static void Write(string path, string content)
{
    File.WriteAllText(path, content.ReplaceLineEndings("\n"), new UTF8Encoding(false));
    Console.WriteLine($"generated {path}");
}

static string TypeParams(int arity) => string.Join(", ", Enumerable.Range(1, arity).Select(i => $"T{i}"));

static string Ordinal(int i) => i switch
{
    1 => "1st",
    2 => "2nd",
    3 => "3rd",
    _ => $"{i}th"
};

static string Header() =>
    """
    // <auto-generated>
    //     Generated by tools/Generate.cs. Do not edit manually: change the generator and run
    //     'dotnet run tools/Generate.cs' from the repository root.
    // </auto-generated>

    """;

static string GenerateUnions()
{
    var sb = new StringBuilder(Header());
    sb.AppendLine("""
                  #nullable enable

                  namespace LeoUnion;
                  """);
    for (int arity = MinArity; arity <= MaxArity; arity++)
    {
        sb.AppendLine();
        sb.AppendLine($$"""
                        /// <summary>
                        ///     A union of {{arity}} case types: a value of this type holds exactly one value of one of
                        ///     <typeparamref name="T1" /> to <typeparamref name="T{{arity}}" />.
                        ///     Values of the case types convert to the union implicitly and a <c>switch</c> expression over the
                        ///     union is checked for exhaustiveness by the compiler.
                        /// </summary>
                        /// <remarks>
                        ///     This is a native C# union: it stores its value as <see cref="object" />, so a value-type case is
                        ///     boxed once when the union is created. Pattern matching does not allocate.
                        ///     The <c>default</c> value holds no case: its <see cref="Value" /> is <see langword="null" />.
                        /// </remarks>
                        """);
        for (int i = 1; i <= arity; i++)
        {
            sb.AppendLine($"/// <typeparam name=\"T{i}\">The {Ordinal(i)} case type.</typeparam>");
        }
        sb.AppendLine($"public union Union<{TypeParams(arity)}>({TypeParams(arity)})");
        sb.AppendLine("""
                      {
                          /// <summary>Returns the string representation of the held value, or an empty string if there is none.</summary>
                          public override string ToString() => Value?.ToString() ?? string.Empty;
                      }
                      """);
    }
    return sb.ToString();
}

static string GenerateContractTests()
{
    // For every arity and every case position: the case converts in, is found by pattern matching
    // (and by no other case), and round-trips through Value, equality and ToString.
    var sb = new StringBuilder(Header());
    sb.AppendLine("""
                  namespace LeoUnion.Tests;

                  public sealed class ContractTests
                  {
                  """);
    for (int arity = MinArity; arity <= MaxArity; arity++)
    {
        string type = $"Union<{string.Join(", ", Enumerable.Range(1, arity).Select(i => $"C{i}"))}>";
        for (int k = 1; k <= arity; k++)
        {
            sb.AppendLine("    [Fact]");
            sb.AppendLine($"    public void Union{arity}_Case{k}()");
            sb.AppendLine("    {");
            sb.AppendLine($"        {type} union = new C{k}({k});");
            sb.AppendLine();
            sb.AppendLine($"        union.Value.Should().Be(new C{k}({k}));");
            sb.AppendLine("        int matched = union switch");
            sb.AppendLine("        {");
            for (int c = 1; c <= arity; c++)
            {
                sb.AppendLine($"            C{c} c{c} => c{c}.Id + {c * 100},");
            }
            sb.AppendLine("        };");
            sb.AppendLine($"        matched.Should().Be({k} + {k * 100});");
            for (int c = 1; c <= arity; c++)
            {
                sb.AppendLine($"        (union is C{c}).Should().Be({(c == k ? "true" : "false")});");
            }
            sb.AppendLine($"        union.Equals(({type}) new C{k}({k})).Should().BeTrue();");
            sb.AppendLine($"        union.Equals(({type}) new C{k}({k + 1})).Should().BeFalse();");
            sb.AppendLine($"        union.ToString().Should().Be(new C{k}({k}).ToString());");
            sb.AppendLine("    }");
            sb.AppendLine();
        }
    }
    sb.AppendLine("}");
    sb.AppendLine();
    for (int c = 1; c <= MaxArity; c++)
    {
        sb.AppendLine($"public readonly record struct C{c}(int Id);");
    }
    return sb.ToString();
}
